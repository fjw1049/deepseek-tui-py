def _target(tool: str, arguments: Any, metadata: dict[str, Any] | None = None) -> str:
    if not isinstance(arguments, dict):
        return ""
    if tool in _UI_TOOLS:
        action = str(arguments.get("action") or "")
        before = (metadata or {}).get("browser_before") or {}
        identity = {k: v for k, v in arguments.items() if k != "timeout_ms"}
        if arguments.get("operation_id"):
            identity = {"action": action, "operation_id": arguments["operation_id"]}
        elif action in {"open", "new_tab"} and before.get("tab_id"):
            identity["tab_id"] = arguments.get("tab_id") or before["tab_id"]
        elif before.get("document_id"):
            identity["page"] = before
            if before.get("target_id"):
                identity.pop("ref", None)
                identity.pop("selector", None)
            # Bare refs/coordinates remain observation-bound unless the runtime
            # identified a stable target. A fresh observation is not a new target.
            if before.get("target_id") or not any(k in arguments for k in ("ref", "x", "y")):
                identity.pop("observation_id", None)
                identity.pop("generation", None)
        digest = hashlib.sha256(
            json.dumps(identity, sort_keys=True, default=str).encode()
        ).hexdigest()[:12]
        return f"{action} [{digest}]"
    return next(
        (str(arguments[key])[:120] for key in _TARGET_KEYS if arguments.get(key)), ""
    )


def _error_text(error: str) -> str:
    """Browser failures arrive as a JSON result; the reason is its content."""
    try:
        data = json.loads(error)
    except ValueError:
        data = None
    text = data.get("content") if isinstance(data, dict) else None
    return " ".join(str(text if text else error).split())[:160]


def without_completion_note(text: str, metadata: dict[str, Any] | None) -> str:
    """The answer as the model wrote it, for anything that feeds model history or grading."""
    note = (metadata or {}).get(COMPLETION_NOTE_KEY)
    if isinstance(note, str) and note and text.endswith(note):
        return text[: -len(note)].rstrip()
    return text


@dataclass
class TurnFacts:
    assistance_requests: list[dict[str, Any]] = field(default_factory=list)
    called_tools: bool = False
    browser_used: bool = False
    cua_used: bool = False
    # (tool, target) -> error; the same call succeeding clears it.
    failures: dict[tuple[str, str], str] = field(default_factory=dict)
    # Reported only when something ran: a turn that never runs anything has nothing to go stale.
    ran: bool = False
    edited_after_run: list[str] = field(default_factory=list)
    pending_reminded: bool = False
    # Absolute paths from before the session; None until the first shell command.
    existing_files: dict[str, tuple[int, int]] | None = None
    approved_removals: set[str] = field(default_factory=set)
    gone_files: list[str] = field(default_factory=list)

    def record(self, tool: str, arguments: Any, *, success: bool, error: str = "",
               metadata: dict[str, Any] | None = None) -> None:
        self.called_tools = True
        self.browser_used |= tool in _BROWSER_TOOLS
        self.cua_used |= tool in CUA_TOOLS
        if tool in _ACTING_TOOLS:
            key = (tool, _target(tool, arguments, metadata))
            if success:
                # Bare refs/selectors may refer to a different page on the next call.
                identified = tool not in _UI_TOOLS or (
                    isinstance(arguments, dict) and (
                        any(arguments.get(k) for k in ("operation_id", "observation_id", "url"))
                        or arguments.get("action") in {"wait", "check_text"}
                        or (
                            ((metadata or {}).get("browser_before") or {}).get("document_id")
                            and (not any(k in arguments for k in ("ref", "x", "y"))
                                 or ((metadata or {}).get("browser_before") or {}).get("target_id"))
                        )
                    )
                )
                if identified:
                    self.failures.pop(key, None)
            else:
                self.failures[key] = _error_text(error)
        if tool == "exec_shell":
            # What a command writes is its output, not an edit made after it ran.
            self.ran = True
            self.edited_after_run.clear()
        elif tool in _FILE_TOOLS and success:
            path = _target(tool, arguments)
            if (path and path not in self.edited_after_run
                    and PurePath(path).suffix.lower() not in _NOT_RUNNABLE):
                self.edited_after_run.append(path)

    def pending(self, metadata: dict[str, Any]) -> list[str]:
        """Label keys for state a person should know about before the turn is called done."""
        pending: list[str] = []
        if self.browser_used:
            browser = metadata.get("browser_service")
            thread = str(metadata.get("runtime_thread_id"))
            state = browser.state(thread) if callable(getattr(browser, "state", None)) else {}
            run = getattr(browser, "runs", {}).get(thread)
            # A closed session keeps its unresolved operations in state only.
            if state.get("unresolved") or (run and run.unresolved):
                pending.append("browser_unresolved")
            if state.get("dialog"):
                pending.append("browser_dialog")
            if state.get("file_chooser"):
                pending.append("browser_file_chooser")
            if run and (getattr(run, "pending_action", None) or getattr(run, "pending_input", None)):
                pending.append("browser_pending")
            if run and run.assistance:
                pending.append("browser_assistance")
        session = metadata.get("cua_session") if self.cua_used else None
        if session is not None:
            if session.unresolved:
                pending.append("cua_unresolved")
            if session.outside_change:
                pending.append("cua_outside_change")
            if session.reset_reason:
                pending.append("cua_reset")
        return pending

    def outcome(
        self, pending: list[str], problems: list[str], locale: str = "zh",
    ) -> dict[str, Any] | None:
        if self.assistance_requests:
            return {"status": "needs_assistance", "remaining": [
                str(r.get("reason") or r.get("questions")) for r in self.assistance_requests
            ], "requests": list(self.assistance_requests)}
        if not self.called_tools and not problems:
            return None
        labels = _labels(locale)
        remaining = [labels[key] for key in pending] + problems + [
            f"{tool} {target}".strip() for tool, target in self.failures
        ]
        if remaining:
            status = "partial"
        elif self.ran and not self.edited_after_run:
            status = "completed_with_evidence"
        else:
            status = "completed_unverified"
        return {"status": status, "remaining": remaining}

    def note(self, pending: list[str], problems: list[str], locale: str = "zh") -> str | None:
        labels = _labels(locale)
        lines = []
        if self.assistance_requests:
            lines.append(labels["pending"] + "; ".join(
                str(r.get("reason") or r.get("questions")) for r in self.assistance_requests
            ))
        if pending:
            lines.append(labels["pending"] + "; ".join(labels[key] for key in pending))
        if self.ran and self.edited_after_run:
            lines.append(labels["edited"] + _listed(self.edited_after_run))
        if self.failures:
            shown = [f"{tool} {target}: {error}".replace("  ", " ")
                     for (tool, target), error in self.failures.items()]
            lines.append(labels["failures"] + _listed(shown))
        if self.gone_files:
            lines.append(labels["gone"] + _listed(self.gone_files))
        if problems:
            lines.append(labels["problems"] + "; ".join(problems))
        if not lines:
            return None
        return "\n".join(["---", labels["title"], *(f"- {line}" for line in lines)])


def _labels(locale: str) -> dict[str, str]:
    return _LABELS["en" if str(locale).startswith("en") else "zh"]


def _listed(items: list[str]) -> str:
    extra = f"; +{len(items) - _SHOWN}" if len(items) > _SHOWN else ""
    return "; ".join(items[:_SHOWN]) + extra
