const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
app.commandLine.appendSwitch('user-data-dir', '/tmp/workspace-components-verification')
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1280, height: 920, show: false, webPreferences: { offscreen: true } })
  const errors = []
  win.webContents.on('console-message', (_e, level, message) => { if (level >= 3) errors.push(message) })
  await win.loadURL('http://127.0.0.1:5188/docs/workspace-visual-audit-2026-09-13/verification/')
  const run = code => win.webContents.executeJavaScript(code)
  await run(`window.addEventListener('unhandledrejection', e => console.error('rejection stack: ' + (e.reason?.stack || e.reason)))`)
  async function waitFor(expression) {
    for (let i=0;i<160;i++) {
      if (await run(`Boolean(${expression})`)) return
      await new Promise(resolve => setTimeout(resolve, 250))
    }
    throw new Error('Timed out: '+expression+'\n'+errors.join('\n'))
  }
  await waitFor('window.audit && window.audit.monaco.editor.getEditors().length && document.querySelector("#diff-fixture .ds-syntax-line span") && document.querySelector("#markdown-fixture .ds-syntax-line span")')
  await run(`(() => {const tab=document.querySelector('[role="tab"]');tab.focus();tab.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));})()`)
  await waitFor('window.audit.store.getState().activeTabId === window.audit.tabs[1].id')
  await run(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true}))`)
  await waitFor('window.audit.store.getState().activeTabId === window.audit.tabs[0].id')
  const keyboardTabs = await run(`document.activeElement.getAttribute('aria-selected') === 'true'`)
  assert.equal(keyboardTabs,true)
  const layout = await run(`(() => {
    const rect = selector => document.querySelector(selector).getBoundingClientRect().height;
    const code = document.querySelector('#diff-fixture tbody tr:nth-child(2) td:last-child');
    return {treeHeader:rect('.ds-workspace-file-tree__header'),tabstrip:rect('.ds-workspace-editor-tabstrip'),diffHeader:rect('.ds-diff-view__header'),codeLineHeight:code.getBoundingClientRect().height,whiteSpace:getComputedStyle(code).whiteSpace,markdownAlign:getComputedStyle(document.querySelector('#markdown-fixture p')).textAlign};
  })()`)
  assert.equal(layout.treeHeader,36)
  assert.equal(layout.tabstrip,36)
  assert.equal(layout.diffHeader,36)
  assert.equal(layout.whiteSpace,'pre')
  assert.equal(layout.markdownAlign,'start')
  await run(`(() => {const a=window.audit; a.store.getState().updateTabContent(a.tabs[0].id,a.tabs[0].content+'\\n// unsaved');})()`)
  await waitFor('document.querySelector(".ds-workspace-editor-tab[data-dirty]")')
  await new Promise(resolve => setTimeout(resolve, 200))
  const dirtyOpacity = await run(`getComputedStyle(document.querySelector('.ds-workspace-editor-tab[data-dirty] .ds-workspace-editor-tab__close')).opacity`)
  await run(`(() => {const e=window.audit.monaco.editor.getEditors()[0]; e.setPosition({lineNumber:100,column:3});e.revealLineInCenter(100);})()`)
  await new Promise(resolve => setTimeout(resolve, 250))
  const before = await run(`({position:window.audit.monaco.editor.getEditors()[0].getPosition(),scroll:window.audit.monaco.editor.getEditors()[0].getScrollTop()})`)
  await run(`window.audit.store.getState().setActiveTab(window.audit.tabs[1].id)`)
  await waitFor('window.audit.monaco.editor.getEditors()[0]?.getModel()?.uri.path === window.audit.tabs[1].id')
  await run(`window.audit.store.getState().setActiveTab(window.audit.tabs[0].id)`)
  await waitFor('window.audit.monaco.editor.getEditors()[0]?.getModel()?.uri.path === window.audit.tabs[0].id')
  await new Promise(resolve => setTimeout(resolve, 250))
  const after = await run(`({position:window.audit.monaco.editor.getEditors()[0].getPosition(),scroll:window.audit.monaco.editor.getEditors()[0].getScrollTop()})`)
  assert.deepEqual(after,before)
  await run(`document.querySelector('[aria-label="编辑"]').click()`)
  await waitFor('!window.audit.monaco.editor.getEditors()[0].getOption(window.audit.monaco.editor.EditorOption.readOnly)')
  const beforeEdit = await run('window.audit.monaco.editor.getEditors()[0].getValue()')
  await run(`(() => {const e=window.audit.monaco.editor.getEditors()[0];e.pushUndoStop();e.executeEdits('verification',[{range:new window.audit.monaco.Range(1,1,1,1),text:'// undo marker\\n'}]);e.pushUndoStop();})()`)
  await run(`window.audit.store.getState().setActiveTab(window.audit.tabs[1].id)`)
  await waitFor('window.audit.monaco.editor.getEditors()[0]?.getModel()?.uri.path === window.audit.tabs[1].id')
  await run(`window.audit.store.getState().setActiveTab(window.audit.tabs[0].id)`)
  await waitFor('window.audit.monaco.editor.getEditors()[0]?.getModel()?.uri.path === window.audit.tabs[0].id')
  const undoAvailable = await run('window.audit.monaco.editor.getEditors()[0].getModel().canUndo()')
  assert.equal(undoAvailable,true)
  await run('window.audit.monaco.editor.getEditors()[0].getModel().undo()')
  assert.equal(await run('window.audit.monaco.editor.getEditors()[0].getValue()'),beforeEdit)
  await run(`document.documentElement.setAttribute('data-theme','dark')`)
  await waitFor('document.querySelector(".monaco-editor.vs-dark")')
  await new Promise(resolve => setTimeout(resolve, 300))
  fs.writeFileSync(path.join(__dirname,'dark.png'),(await win.webContents.capturePage()).toPNG())
  await run(`document.documentElement.setAttribute('data-theme','light')`)
  await waitFor('document.querySelector(".monaco-editor.vs")')
  await run(`window.audit.monaco.editor.getEditors()[0].setScrollTop(0)`)
  await new Promise(resolve => setTimeout(resolve, 300))
  fs.writeFileSync(path.join(__dirname,'light.png'),(await win.webContents.capturePage()).toPNG())
  await run(`document.querySelector('[aria-label="Split diff"]').click()`)
  await waitFor('document.querySelectorAll("#diff-fixture colgroup col").length === 4')
  win.setSize(900,760)
  await new Promise(resolve => setTimeout(resolve, 300))
  const narrow = await run(`({viewport:innerWidth,document:document.documentElement.scrollWidth,diff:document.querySelector('#diff-fixture .ds-change-inspector__code').clientWidth,content:document.querySelector('#diff-fixture .ds-change-inspector__code').scrollWidth})`)
  assert.equal(narrow.document,narrow.viewport)
  assert.ok(narrow.content > narrow.diff)
  fs.writeFileSync(path.join(__dirname,'narrow-split.png'),(await win.webContents.capturePage()).toPNG())
  await run(`document.querySelector('[aria-label="自动换行"]').click()`)
  await waitFor('document.querySelector("#diff-fixture .ds-diff-view[data-wrap]")')
  const wrapped = await run(`(() => {const v=document.querySelector('#diff-fixture .ds-change-inspector__code');return {viewport:v.clientWidth,content:v.scrollWidth,whitespace:getComputedStyle(document.querySelector('#diff-fixture .ds-diff-code')).whiteSpace}})()`)
  assert.ok(wrapped.content <= wrapped.viewport + 1)
  assert.equal(wrapped.whitespace,'pre-wrap')
  fs.writeFileSync(path.join(__dirname,'narrow-wrapped.png'),(await win.webContents.capturePage()).toPNG())
  await run(`window.audit.store.getState().setActiveTab(window.audit.tabs[2].id)`)
  await waitFor('document.querySelector("#editor-fixture .ds-markdown-doc-page")')
  await run(`document.querySelectorAll('.ds-workspace-document-mode button')[1].click()`)
  await waitFor('document.querySelector("#editor-fixture .monaco-editor")')
  await run(`document.querySelectorAll('.ds-workspace-document-mode button')[0].click()`)
  await waitFor('document.querySelector("#editor-fixture .ds-markdown-doc-page")')
  await run(`window.audit.store.getState().closeTab(window.audit.tabs[0].id)`)
  await waitFor('!window.audit.monaco.editor.getModels().some(m => m.uri.path === window.audit.tabs[0].id)')
  assert.equal(dirtyOpacity,'1')
  const result = {layout,narrow,wrapped,keyboardTabs,dirtyOpacity,before,after,undoAvailable,themeSwitch:true,previewRoundTrip:true,closedModelDisposed:true,errors}
  fs.writeFileSync(path.join(__dirname,'results.json'),JSON.stringify(result,null,2)+'\n')
  console.log(JSON.stringify(result,null,2))
  app.quit()
}).catch(error => {console.error(error);app.exit(1)})
